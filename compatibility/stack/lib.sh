# Shared by the stack acceptance suites. `compute stack test` runs each
# `<suite>.sh` with:
#
#   STACK_LOCK     the lock under test (compute.stack-lock@1)
#   STACK_SOURCES  <name>/ checkouts of every source at its locked commit,
#                  verified against the lock before any suite runs
#   STACK_OUT      this suite's output directory; the suite writes result.json
#   STACK_WORK     the run's work directory, shared by the suites in order
#   STACK_HARNESS  this directory
#
# A suite reuses the tests its sources already have, at their locked commits;
# it never reaches a developer's checkout. Its verdict is result.json
# (`{status, passed, failed, skipped, artifacts, detail}`) and its exit code;
# both must say passed.
set -euo pipefail

src() { printf '%s/%s' "$STACK_SOURCES" "$1"; }

# The exact version the lock pins for a package.
lock_version() {
  node -e 'const l=JSON.parse(require("fs").readFileSync(process.argv[1],"utf8"));const p=l.packages.find(p=>p.package===process.argv[2]);if(!p)process.exit(3);console.log(p.version)' "$STACK_LOCK" "$1"
}
lock_integrity() {
  node -e 'const l=JSON.parse(require("fs").readFileSync(process.argv[1],"utf8"));console.log(l.packages.find(p=>p.package===process.argv[2]).integrity)' "$STACK_LOCK" "$1"
}
lock_commit() {
  node -e 'const l=JSON.parse(require("fs").readFileSync(process.argv[1],"utf8"));console.log(l.sources.find(s=>s.name===process.argv[2]).commit)' "$STACK_LOCK" "$1"
}

# result <status> <passed> <failed> <skipped> <detail> [artifact=path ...]
result() {
  local status=$1 passed=$2 failed=$3 skipped=$4 detail=$5
  shift 5
  node -e '
    const [out, status, passed, failed, skipped, detail, ...pairs] = process.argv.slice(1);
    const crypto = require("node:crypto"), fs = require("node:fs");
    const artifacts = {};
    for (const pair of pairs) {
      const [name, file] = pair.split(/=(.*)/s);
      if (fs.existsSync(file)) artifacts[name] = "sha256:" + crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex");
    }
    fs.writeFileSync(out + "/result.json", JSON.stringify({ status, passed: +passed, failed: +failed, skipped: +skipped, artifacts, detail }, null, 1) + "\n");
  ' "$STACK_OUT" "$status" "$passed" "$failed" "$skipped" "$detail" "$@"
  echo "result: $status passed=$passed failed=$failed skipped=$skipped: $detail"
  [ "$status" = passed ]
}

# Counts of `test result:` lines in cargo test output.
cargo_counts() {
  awk '/^test result:/ { for (i = 1; i <= NF; i++) { if ($(i+1) ~ /^passed;?$/) p += $i; if ($(i+1) ~ /^failed;?$/) f += $i; if ($(i+1) ~ /^ignored;?$/) s += $i } } END { printf "%d %d %d\n", p, f, s }' "$1"
}

# One Cargo target directory per source, kept in the run's work directory.
cargo_target() { printf '%s/target/%s' "$STACK_WORK" "$1"; }

# The invoice desk at its locked commit with a bridge generated by the CLI
# packed from the locked appboundry, and the stack's own @appport/sdk.
# Built once per lock into $STACK_WORK/desk; later suites of the run reuse it.
prepare_desk() {
  local desk="$STACK_WORK/desk" pack="$STACK_WORK/pack"
  local stamp; stamp=$(sha256sum "$STACK_LOCK" | cut -d' ' -f1)
  if [ "$(cat "$desk/.stack-prepared" 2>/dev/null)" = "$stamp" ]; then return; fi
  rm -rf "$desk" "$pack"; mkdir -p "$pack"
  # appboundry built from its frozen lockfile in a copy, so the checkout stays as locked.
  local build="$STACK_WORK/appboundry-build"
  rm -rf "$build"; cp -r "$(src appboundry)" "$build"
  (cd "$build" && pnpm install --frozen-lockfile --ignore-scripts && pnpm run build) >"$STACK_WORK/appboundry-build.log" 2>&1 \
    || { tail -40 "$STACK_WORK/appboundry-build.log"; return 1; }
  # The CLI, staged and packed by appboundry's own release staging; nothing is published.
  node --input-type=module -e '
    const [repo, out] = process.argv.slice(1);
    const { join } = await import("node:path");
    const { execFileSync } = await import("node:child_process");
    const { mkdir } = await import("node:fs/promises");
    const { stageReleasePackage } = await import(join(repo, "scripts/release-stage.mjs"));
    const staged = join(out, "staged-cli");
    await mkdir(staged, { recursive: true });
    await stageReleasePackage("packages/cli", staged);
    const report = JSON.parse(execFileSync("npm", ["pack", "--json", "--pack-destination", out], { cwd: staged, encoding: "utf8" }))[0];
    console.log(`packed ${report.name}@${report.version} ${report.filename} ${report.integrity}`);
  ' "$build" "$pack"
  local cli; cli=$(ls "$pack"/appport-*.tgz)
  local sdk; sdk=$(lock_version @appport/sdk)
  cp -r "$(src invoice-desk)" "$desk"
  (
    cd "$desk"
    # The desk's package-lock.json does not satisfy its package.json (npm ci
    # refuses it): resolve without it, as the L1 experiment does.
    npm install --no-package-lock --no-audit --no-fund >"$STACK_WORK/desk-install.log" 2>&1
    npm install --no-save --no-package-lock --no-audit --no-fund "$cli" "@appport/sdk@$sdk" >>"$STACK_WORK/desk-install.log" 2>&1
    test "$(node -p 'JSON.parse(require("fs").readFileSync("node_modules/@appport/sdk/package.json","utf8")).version')" = "$sdk"
    ./node_modules/.bin/appport add --name "Mini Invoice Approval Desk" --id com.example.invoice-desk --version 1.0.0 \
      --capability invoices,invoices.id,invoices.id.status --no-build --no-start --no-verify </dev/null >"$STACK_WORK/appport-add.txt"
    sha256sum appboundry.contract.json appport.bridge.json appport/server.ts appport/runtime/bridge.ts appport/implementation/index.ts >"$STACK_WORK/generated.sha256"
  )
  echo "$stamp" >"$desk/.stack-prepared"
}

# The L1 experiment's harness from the locked stack-agent, with the generic
# MCP client's dependencies installed beside it.
L1=docs/research/agent-runtime-primitives/experiments/stack-agent/appport-live-l1/artifacts/harness
prepare_l1_harness() {
  local tools="$STACK_WORK/l1-harness"
  local stamp; stamp=$(sha256sum "$STACK_LOCK" | cut -d' ' -f1)
  if [ "$(cat "$tools/.stack-prepared" 2>/dev/null)" = "$stamp" ]; then return; fi
  rm -rf "$tools"; cp -r "$(src stack-agent)/$L1" "$tools"
  (cd "$tools" && npm init -y >/dev/null && npm install --no-audit --no-fund @modelcontextprotocol/sdk@1.31.0 better-sqlite3@13.0.3 >"$STACK_WORK/l1-harness-install.log" 2>&1)
  echo "$stamp" >"$tools/.stack-prepared"
}
